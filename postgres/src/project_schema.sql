CREATE SCHEMA IF NOT EXISTS project;

CREATE TABLE IF NOT EXISTS project.project_master
(
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE VARCHAR(50) DEFAULT '',
    DESCRIPTION TEXT DEFAULT '',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP 
);

CREATE TABLE IF NOT EXISTS project.project_members
(
    ID BIGINT REFERENCES project.project_master(ID),
    SHORTCODE VARCHAR(10) REFERENCES public.MAPPING(SHORTCODE),
    ACKNOWLEDGED BOOLEAN DEFAULT FALSE,
    REGISTERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(ID, SHORTCODE)
);

CREATE TABLE IF NOT EXISTS project.project_type
(
    ID BIGINT REFERENCES project.project_master(ID),
    TYPE VARCHAR(50),
    REGISTERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(ID, TYPE)
);

CREATE TABLE IF NOT EXISTS project.project_bom
(
    ID BIGINT REFERENCES project.project_master(ID),
    PURCHASE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    DESCRIPTION TEXT,
    SOURCE TEXT,
    PRICE MONEY,            
    REGISTERED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    COMPLETED_AT TIMESTAMP
);
